export function gaKey(weeks: number, days: number): string {
  return weeks + '.' + days;
}

export function calcPercentileWithRef(pesoKg: number, ref: number[]): number {
  // ref = [P3, P5, P10, P50, P90, P95, P97]
  const [p3, p5, p10, p50, p90, p95, p97] = ref;
  if (pesoKg < p3) return Math.max(3 * (pesoKg / p3), 0.1);
  if (pesoKg < p5)  return 3 + (5 - 3) * (pesoKg - p3) / (p5 - p3);
  if (pesoKg < p10) return 5 + (10 - 5) * (pesoKg - p5) / (p10 - p5);
  if (pesoKg < p50) return 10 + (50 - 10) * (pesoKg - p10) / (p50 - p10);
  if (pesoKg < p90) return 50 + (90 - 50) * (pesoKg - p50) / (p90 - p50);
  if (pesoKg < p95) return 90 + (95 - 90) * (pesoKg - p90) / (p95 - p90);
  if (pesoKg < p97) return 95 + (97 - 95) * (pesoKg - p95) / (p97 - p95);
  return Math.min(97 + 3 * (1 - (p97 / pesoKg)), 99.9);
}

export type IntergrowthInput = {
  weeks: number;
  days: number;
  peso: number; // in grams
  sexo: string; // 'M' or 'F'
};

export type IntergrowthResult = {
  percentil: number;
  p50: number; // in kg
  ref: number[];
  pesoKg: number;
  classificationRaw: 'iugr' | 'sga' | 'aga' | 'lga';
};

export function computeIntergrowthPercentile(input: IntergrowthInput): IntergrowthResult | null {
  const { weeks, days, peso, sexo } = input;
  const key = gaKey(weeks, days);
  const table = IG[sexo === 'M' ? 'M' : 'F'];
  const ref = table[key];
  if (!ref) return null;

  const pesoKg = peso / 1000;
  const percentil = calcPercentileWithRef(pesoKg, ref);
  const p50 = ref[3]; 

  let classificationRaw: 'iugr' | 'sga' | 'aga' | 'lga' = 'aga';
  if (percentil < 3) classificationRaw = 'iugr';
  else if (percentil < 10) classificationRaw = 'sga';
  else if (percentil > 90) classificationRaw = 'lga';

  return { percentil, p50, ref, pesoKg, classificationRaw };
}
